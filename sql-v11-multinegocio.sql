create or replace function public.validar_telefonos()
returns trigger language plpgsql as $$
begin
  new.telefono := nullif(trim(new.telefono), '');
  new.telefono2 := nullif(trim(new.telefono2), '');
  if new.telefono2 is not null and new.telefono2 = new.telefono then
    raise exception 'El segundo teléfono no puede ser igual al primero.';
  end if;
  if exists (
    select 1 from clientes c
    where c.negocio_id = new.negocio_id
      and c.id <> coalesce(new.id, -1)
      and (c.telefono in (new.telefono, new.telefono2)
           or c.telefono2 in (new.telefono, new.telefono2))
  ) then
    raise exception 'Ese teléfono ya pertenece a otro cliente.';
  end if;
  return new;
end $$;

create or replace function public.anular_servicio(p_servicio_id bigint, p_motivo text)
returns void language plpgsql security definer set search_path = public as $$
declare
  s jsonb; c jsonb; v_cita bigint; v_nombre text; v_negocio bigint := public.mi_negocio();
begin
  if auth.uid() is null then raise exception 'Debes iniciar sesión.'; end if;
  if v_negocio is null then raise exception 'Tu usuario no tiene un negocio asignado.'; end if;
  if coalesce(trim(p_motivo), '') = '' then raise exception 'Escribe el motivo de la cancelación.'; end if;

  select to_jsonb(x) into s from servicios x
  where x.id = p_servicio_id and x.negocio_id = v_negocio for update;
  if s is null then raise exception 'El servicio no existe o ya fue cancelado.'; end if;

  v_cita := nullif(s ->> 'cita_id', '')::bigint;
  if v_cita is not null then select to_jsonb(x) into c from citas x where x.id = v_cita and x.negocio_id = v_negocio; end if;
  select nombre into v_nombre from tipos_servicio where id = nullif(s ->> 'tipo_id', '')::bigint;

  insert into servicios_anulados
    (negocio_id, servicio_id, cita_id, mascota_id, fecha, servicio, precio_cobrado, medicado, datos, motivo, anulado_por, anulado_por_id)
  values
    (v_negocio, p_servicio_id, v_cita,
     coalesce(nullif(s ->> 'mascota_id', '')::bigint, nullif(c ->> 'mascota_id', '')::bigint),
     nullif(s ->> 'fecha', '')::date, v_nombre, nullif(s ->> 'precio_cobrado', '')::numeric,
     coalesce((s ->> 'medicado')::boolean, false), s, trim(p_motivo), usuario_actual(), auth.uid());

  delete from servicios where id = p_servicio_id and negocio_id = v_negocio;

  if v_cita is not null then
    update citas set estado = 'cancelada', cancelada_por = usuario_actual(),
                     cancelada_en = now(), motivo_cancelacion = trim(p_motivo)
    where id = v_cita and negocio_id = v_negocio;
  end if;
end $$;

create or replace function public.cancelar_cita(p_cita_id bigint, p_motivo text)
returns void language plpgsql security definer set search_path = public as $$
declare v_serv bigint; v_negocio bigint := public.mi_negocio();
begin
  if auth.uid() is null then raise exception 'Debes iniciar sesión.'; end if;
  if v_negocio is null then raise exception 'Tu usuario no tiene un negocio asignado.'; end if;
  if coalesce(trim(p_motivo), '') = '' then raise exception 'Escribe el motivo de la cancelación.'; end if;

  select id into v_serv from servicios where cita_id = p_cita_id and negocio_id = v_negocio limit 1;
  if v_serv is not null then
    perform anular_servicio(v_serv, p_motivo);
  else
    update citas set estado = 'cancelada', cancelada_por = usuario_actual(),
                     cancelada_en = now(), motivo_cancelacion = trim(p_motivo)
    where id = p_cita_id and negocio_id = v_negocio and estado <> 'cancelada';
    if not found then raise exception 'La cita no existe o ya estaba cancelada.'; end if;
  end if;
end $$;

create or replace function public.renombrar_grupo_en_descartes()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if new.nombre is distinct from old.nombre then
    update public.pendientes_descartados set grupo = new.nombre
    where grupo = old.nombre and negocio_id = new.negocio_id;
  end if;
  return new;
end $$;

create or replace function public.crear_servicio_al_completar()
returns trigger language plpgsql as $$
begin
  if tg_op = 'UPDATE' then
    if old.estado = 'realizada' and new.estado <> 'realizada' then
      if new.estado = 'cancelada' and not exists (select 1 from servicios where cita_id = new.id) then
        return null;
      end if;
      raise exception 'Una cita realizada no se puede reabrir. Corrige el servicio desde el historial.';
    end if;
    if old.estado = 'realizada' then
      return null;
    end if;
  end if;
  if new.estado = 'realizada' then
    if new.tipo_id is null then
      raise exception 'Elige el servicio de la cita antes de marcarla como realizada.';
    end if;
    insert into servicios (negocio_id, mascota_id, tipo_id, guia_id, cita_id, fecha, precio_cobrado, notas,
                           medicado, recargo_medicado)
    values (new.negocio_id, new.mascota_id, new.tipo_id, new.guia_id, new.id,
            coalesce((new.fecha_hora at time zone 'America/Bogota')::date,
                     (now() at time zone 'America/Bogota')::date),   -- el día de la cita
            coalesce(new.precio_cobrado, new.precio_acordado), new.notas_servicio,
            new.medicado, case when new.medicado then new.recargo_medicado end);
  end if;
  return null;
end $$;

