-- Usuario nuevo: SOLO entra si tiene invitación; queda en el negocio y con el rol de la invitación.
create or replace function public.crear_perfil_usuario()
returns trigger language plpgsql security definer set search_path = public as $$
declare v_inv public.invitaciones%rowtype;
begin
  if tg_op = 'INSERT' then
    select * into v_inv from public.invitaciones where correo = lower(new.email);
    if not found and not exists (select 1 from public.perfiles where id = new.id) then
      raise exception 'El correo % no tiene una invitación. Pide al administrador de tu negocio que te invite.', new.email;
    end if;
    insert into public.perfiles (id, correo, nombre, negocio_id, rol)
    values (new.id, new.email, nullif(trim(new.raw_user_meta_data ->> 'nombre'), ''),
            v_inv.negocio_id, coalesce(v_inv.rol, 'empleado'))
    on conflict (id) do update set correo = excluded.correo,
                                   nombre = coalesce(excluded.nombre, public.perfiles.nombre);
    delete from public.invitaciones where correo = lower(new.email);
  else
    update public.perfiles
       set correo = new.email,
           nombre = coalesce(nullif(trim(new.raw_user_meta_data ->> 'nombre'), ''), nombre)
     where id = new.id;
  end if;
  return new;
end $$;

-- 11) Invitar usuarios y crear negocios -----------------------------------
-- El administrador invita a su negocio; DALU puede invitar a cualquiera.
create or replace function public.invitar_usuario(p_correo text, p_rol text default 'empleado', p_negocio_id bigint default null)
returns text language plpgsql security definer set search_path = public as $$
declare
  v_correo text := lower(trim(p_correo));
  v_negocio bigint;
  v_usuario uuid;
  v_actual bigint;
begin
  if auth.uid() is null then raise exception 'Debes iniciar sesión.'; end if;
  v_negocio := case when public.es_dalu() and p_negocio_id is not null then p_negocio_id else public.mi_negocio() end;
  if v_negocio is null then raise exception 'Tu usuario no tiene un negocio asignado.'; end if;
  if not (public.es_dalu() or (public.es_administrador() and v_negocio = public.mi_negocio())) then
    raise exception 'Solo el administrador puede invitar usuarios.';
  end if;
  if coalesce(p_rol, '') not in ('administrador', 'empleado') then raise exception 'Rol no válido.'; end if;
  if v_correo !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' then raise exception 'Escribe un correo válido.'; end if;

  -- ¿Ya tiene cuenta? Se asigna directo (solo si no pertenece a otro negocio).
  select id into v_usuario from auth.users where lower(email) = v_correo;
  if v_usuario is not null then
    select negocio_id into v_actual from public.perfiles where id = v_usuario;
    if v_actual is not null then
      raise exception 'Ese correo ya tiene acceso a un negocio y no se puede invitar.';
    end if;
    insert into public.perfiles (id, correo, negocio_id, rol) values (v_usuario, v_correo, v_negocio, p_rol)
    on conflict (id) do update set negocio_id = excluded.negocio_id, rol = excluded.rol;
    return 'asignado';
  end if;

  if exists (select 1 from public.invitaciones where correo = v_correo and negocio_id <> v_negocio)
     and not public.es_dalu() then
    raise exception 'Ese correo ya tiene una invitación pendiente de otro negocio.';
  end if;
  insert into public.invitaciones (correo, negocio_id, rol, creado_por)
  values (v_correo, v_negocio, p_rol, auth.uid())
  on conflict (correo) do update set negocio_id = excluded.negocio_id, rol = excluded.rol,
                                     creado_por = excluded.creado_por, creado_en = now();
  return 'invitado';
end $$;

-- Solo DALU: crea el negocio, le copia los servicios y recordatorios base, e invita a su administrador.
create or replace function public.crear_negocio(p_nombre text, p_slug text, p_correo_admin text)
returns bigint language plpgsql security definer set search_path = public as $$
declare v_id bigint;
begin
  if not public.es_dalu() then raise exception 'Solo DALU puede crear negocios.'; end if;
  insert into public.negocios (nombre, slug) values (trim(p_nombre), lower(trim(p_slug)))
  returning id into v_id;

  insert into public.grupos_recordatorio (negocio_id, nombre, frecuencia_dias)
  select v_id, nombre, frecuencia_dias from public.grupos_recordatorio where negocio_id = 1;
  insert into public.tipos_servicio (negocio_id, nombre, grupo_id)
  select v_id, t.nombre, g2.id
  from public.tipos_servicio t
  join public.grupos_recordatorio g on g.id = t.grupo_id
  join public.grupos_recordatorio g2 on g2.negocio_id = v_id and g2.nombre = g.nombre
  where t.negocio_id = 1;

  perform public.invitar_usuario(p_correo_admin, 'administrador', v_id);
  return v_id;
end $$;

