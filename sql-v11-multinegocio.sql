-- 7) Un dato no puede apuntar a un dato de otro negocio --------------------
create or replace function public.verificar_mismo_negocio()
returns trigger language plpgsql security definer set search_path = public as $$
declare v_padre bigint; v_id bigint;
begin
  v_id := nullif(to_jsonb(new) ->> tg_argv[1], '')::bigint;
  if v_id is null then return new; end if;
  execute format('select negocio_id from public.%I where id = $1', tg_argv[0]) into v_padre using v_id;
  if v_padre is not null and v_padre <> new.negocio_id then
    raise exception 'Ese dato pertenece a otro negocio.';
  end if;
  return new;
end $$;

