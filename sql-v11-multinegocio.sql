revoke all on public.pagos from anon;
grant select, insert, update, delete on public.pagos to authenticated;

-- 12) Archivos: cada negocio en su carpeta (logo/1/..., videos/1/...) ------
-- Los archivos que ya existen (sin carpeta) quedan de Pet Garden.
create or replace function public.carpeta_es_mia(p_nombre text)
returns boolean language sql stable security definer set search_path = public as $$
  select (storage.foldername(p_nombre))[1] = public.mi_negocio()::text
      or ((storage.foldername(p_nombre))[1] is null and public.mi_negocio() = 1);
$$;
grant execute on function public.carpeta_es_mia(text) to authenticated;

do $$
declare r record;
begin
  for r in
    select policyname from pg_policies
    where schemaname = 'storage' and tablename = 'objects'
      and (policyname ilike 'logo%' or policyname ilike 'videos%' or policyname like 'archivos_%')
  loop
    execute format('drop policy %I on storage.objects', r.policyname);
  end loop;
end $$;
create policy "archivos_ver" on storage.objects for select to anon, authenticated
  using (bucket_id in ('logo', 'videos'));
create policy "archivos_subir" on storage.objects for insert to authenticated
  with check (bucket_id in ('logo', 'videos') and public.carpeta_es_mia(name)
              and (bucket_id <> 'logo' or public.es_administrador()));
create policy "archivos_cambiar" on storage.objects for update to authenticated
  using (bucket_id in ('logo', 'videos') and public.carpeta_es_mia(name)
         and (bucket_id <> 'logo' or public.es_administrador()))
  with check (bucket_id in ('logo', 'videos') and public.carpeta_es_mia(name)
              and (bucket_id <> 'logo' or public.es_administrador()));
create policy "archivos_borrar" on storage.objects for delete to authenticated
  using (bucket_id in ('logo', 'videos') and public.carpeta_es_mia(name) and public.es_administrador());

commit;

