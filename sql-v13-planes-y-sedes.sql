  using (negocio_id = (select public.mi_negocio()) and array[sede_id] <@ (select public.mis_sedes()));

-- 8) Vistas con sede ---------------------------------------------------------
drop view if exists public.agenda;
drop view if exists public.precios_sugeridos;
drop view if exists public.precio_habitual;

create view public.precio_habitual with (security_invoker = true) as
SELECT DISTINCT ON (mascota_id, tipo_id, sede_id) mascota_id, tipo_id, sede_id, precio
FROM (
  SELECT s.mascota_id, s.tipo_id, s.sede_id, (s.precio_cobrado - COALESCE(s.recargo_medicado, 0)) AS precio,
         s.fecha::timestamp AS cuando
  FROM public.servicios s WHERE s.precio_cobrado IS NOT NULL
  UNION ALL
  SELECT c.mascota_id, c.tipo_id, c.sede_id, (c.precio_acordado - COALESCE(c.recargo_medicado, 0)),
         (c.fecha_hora AT TIME ZONE 'America/Bogota')
  FROM public.citas c
  WHERE c.estado = 'pendiente' AND c.precio_acordado IS NOT NULL AND c.tipo_id IS NOT NULL
) x
ORDER BY mascota_id, tipo_id, sede_id, cuando DESC;

create view public.precios_sugeridos with (security_invoker = true) as
SELECT mascota_id, tipo_id, servicio, precio_habitual, precio_raza, recargo_medicado,
       COALESCE(precio_habitual, precio_raza) AS precio_sugerido,
       CASE WHEN precio_habitual IS NOT NULL THEN 'mascota' WHEN precio_raza IS NOT NULL THEN 'raza' END AS origen,
       sede_id
FROM (
  SELECT m.id AS mascota_id, t.id AS tipo_id, sd.id AS sede_id, t.nombre AS servicio, ph.precio AS precio_habitual,
         CASE t.nombre WHEN 'Baño' THEN ps.precio_bano WHEN 'Corte' THEN ps.precio_corte
                       WHEN 'Corte y baño' THEN ps.precio_corte_bano WHEN 'Uñas' THEN ps.precio_unas END AS precio_raza,
         ps.recargo_medicado
  FROM public.mascotas m
  JOIN public.tipos_servicio t ON t.negocio_id = m.negocio_id
  JOIN public.sedes sd ON sd.negocio_id = m.negocio_id
  LEFT JOIN public.precios_sede ps ON ps.raza_id = m.raza_id AND ps.sede_id = sd.id
  LEFT JOIN public.precio_habitual ph ON ph.mascota_id = m.id AND ph.tipo_id = t.id AND ph.sede_id = sd.id
) x;

create view public.agenda with (security_invoker = true) as
SELECT ci.id, ci.fecha_hora, ci.estado, ci.motivo, ci.tipo_id, ci.precio_acordado, ci.precio_cobrado, ci.medicado,
       ci.recargo_medicado, gu.nombre AS guia, c.id AS cliente_id, c.nombre AS cliente, c.telefono, c.telefono2,
       m.id AS mascota_id, m.nombre AS mascota, t.nombre AS servicio,
       COALESCE(ci.precio_acordado, ps.precio_sugerido) AS precio,
       ci.sede_id, sd.nombre AS sede
FROM public.citas ci
JOIN public.mascotas m ON m.id = ci.mascota_id
JOIN public.clientes c ON c.id = m.cliente_id
JOIN public.sedes sd ON sd.id = ci.sede_id
LEFT JOIN public.tipos_servicio t ON t.id = ci.tipo_id
LEFT JOIN public.guias gu ON gu.id = ci.guia_id
LEFT JOIN public.precios_sugeridos ps ON ps.mascota_id = ci.mascota_id AND ps.tipo_id = ci.tipo_id AND ps.sede_id = ci.sede_id;

create or replace view public.historial with (security_invoker = true) as
SELECT s.id, s.fecha, c.id AS cliente_id, c.nombre AS cliente, m.id AS mascota_id, m.nombre AS mascota,
       t.nombre AS servicio, gu.nombre AS guia, s.precio_cobrado, s.notas, s.medicado,
       s.sede_id, sd.nombre AS sede
FROM public.servicios s
JOIN public.mascotas m ON m.id = s.mascota_id
JOIN public.clientes c ON c.id = m.cliente_id
JOIN public.tipos_servicio t ON t.id = s.tipo_id
LEFT JOIN public.guias gu ON gu.id = s.guia_id
LEFT JOIN public.sedes sd ON sd.id = s.sede_id;

create or replace view public.pendientes with (security_invoker = true) as
SELECT c.id AS cliente_id, c.nombre AS cliente, c.telefono, m.id AS mascota_id, m.nombre AS mascota, g.nombre AS grupo,
       max(s.fecha) AS ultima_fecha, (max(s.fecha) + g.frecuencia_dias) AS proxima_fecha,
       (CURRENT_DATE - (max(s.fecha) + g.frecuencia_dias)) AS dias_de_retraso,
       (array_agg(s.sede_id ORDER BY s.fecha DESC, s.id DESC))[1] AS ultima_sede_id
FROM public.servicios s
JOIN public.mascotas m ON m.id = s.mascota_id
JOIN public.clientes c ON c.id = m.cliente_id
JOIN public.tipos_servicio t ON t.id = s.tipo_id
JOIN public.grupos_recordatorio g ON g.id = t.grupo_id
WHERE c.activo
GROUP BY c.id, c.nombre, c.telefono, m.id, m.nombre, g.id, g.nombre, g.frecuencia_dias
HAVING (max(s.fecha) + g.frecuencia_dias) <= CURRENT_DATE;

-- Razas con los precios de cada sede (la pantalla pide los de la sede en la que estás)
create or replace view public.razas_sede with (security_invoker = true) as
SELECT sd.id AS sede_id, r.id, r.nombre, r.especie,
       ps.precio_bano, ps.precio_corte, ps.precio_corte_bano, ps.precio_unas, ps.recargo_medicado
FROM public.razas r
JOIN public.sedes sd ON sd.negocio_id = r.negocio_id
LEFT JOIN public.precios_sede ps ON ps.raza_id = r.id AND ps.sede_id = sd.id;

revoke all on public.precio_habitual, public.precios_sugeridos, public.agenda, public.historial,
              public.pendientes, public.razas_sede from anon;
grant select on public.precio_habitual, public.precios_sugeridos, public.agenda, public.historial,
               public.pendientes, public.razas_sede to authenticated, service_role;

-- 9) Funciones que ahora tienen en cuenta la sede ---------------------------
create or replace function public.crear_servicio_al_completar()
returns trigger language plpgsql as $$
begin
  if tg_op = 'UPDATE' then
    if old.estado = 'realizada' and new.estado <> 'realizada' then
      if new.estado = 'cancelada' and not exists (select 1 from servicios where cita_id = new.id) then
        return null;
      end if;
      raise exception 'Una cita realizada no se puede reabrir. Corrige el servicio desde el historial.';
    end if;
    if old.estado = 'realizada' then
      return null;
    end if;
  end if;
  if new.estado = 'realizada' then
    if new.tipo_id is null then
      raise exception 'Elige el servicio de la cita antes de marcarla como realizada.';
    end if;
    insert into servicios (negocio_id, sede_id, mascota_id, tipo_id, guia_id, cita_id, fecha, precio_cobrado, notas,
                           medicado, recargo_medicado)
    values (new.negocio_id, new.sede_id, new.mascota_id, new.tipo_id, new.guia_id, new.id,
            coalesce((new.fecha_hora at time zone 'America/Bogota')::date,
                     (now() at time zone 'America/Bogota')::date),
            coalesce(new.precio_cobrado, new.precio_acordado), new.notas_servicio,
            new.medicado, case when new.medicado then new.recargo_medicado end);
  end if;
  return null;
end $$;

-- Agendar: ahora recibe la sede (si no llega, se usa la predeterminada de quien agenda)
drop function if exists public.registrar_cita(text, text, text, text, bigint, bigint, timestamptz, numeric, text, text, boolean, numeric);
drop function if exists public.registrar_cita(text, text, text, text, bigint, bigint, timestamptz, numeric, text, text, boolean, numeric, bigint);
create function public.registrar_cita(p_cliente_nombre text, p_telefono text, p_mascota_nombre text, p_especie text,
  p_raza_id bigint, p_tipo_id bigint, p_fecha_hora timestamptz, p_precio numeric, p_motivo text default null,
  p_telefono2 text default null, p_medicado boolean default false, p_recargo numeric default null, p_sede_id bigint default null)
returns table(o_cita_id bigint, o_mascota_id bigint, o_cliente_id bigint, o_mascota_nueva boolean, o_cliente_nuevo boolean)
language plpgsql set search_path = public as $$
declare v_cliente bigint; v_mascota bigint; v_cita bigint;
        v_cnuevo boolean := false; v_mnueva boolean := false;
        v_tel2 text := nullif(trim(p_telefono2), '');
        v_med boolean := coalesce(p_medicado, false);
        v_sede bigint := coalesce(p_sede_id, public.mi_sede_predeterminada());
begin
  if coalesce(trim(p_telefono), '') = '' then
    raise exception 'El teléfono es obligatorio para identificar al cliente';
  end if;
  if v_sede is null or not (v_sede = any(public.mis_sedes())) then
    raise exception 'No tienes acceso a esa sede.';
  end if;
  select id into v_cliente from clientes where telefono = p_telefono or telefono2 = p_telefono limit 1;
  if v_cliente is null then
    insert into clientes (nombre, telefono, telefono2) values (p_cliente_nombre, p_telefono, v_tel2) returning id into v_cliente;
    v_cnuevo := true;
  else
    update clientes set activo = true where id = v_cliente and not activo;
    if v_tel2 is not null then
      update clientes set telefono2 = v_tel2 where id = v_cliente and telefono2 is null and telefono is distinct from v_tel2;
    end if;
  end if;
  select id into v_mascota from mascotas
  where mascotas.cliente_id = v_cliente and lower(mascotas.nombre) = lower(p_mascota_nombre) limit 1;
  if v_mascota is null then
    insert into mascotas (cliente_id, raza_id, nombre, especie) values (v_cliente, p_raza_id, p_mascota_nombre, p_especie)
    returning id into v_mascota;
    v_mnueva := true;
  end if;
  insert into citas (sede_id, mascota_id, tipo_id, fecha_hora, motivo, precio_acordado, medicado, recargo_medicado)
  values (v_sede, v_mascota, p_tipo_id, p_fecha_hora, p_motivo, p_precio, v_med, case when v_med then p_recargo end)
  returning id into v_cita;
  return query select v_cita, v_mascota, v_cliente, v_mnueva, v_cnuevo;
end $$;

