-- Asignaciones: cada quien ve las suyas; el administrador maneja las de su empresa.
drop policy if exists "usuarios_sedes_ver" on public.usuarios_sedes;
create policy "usuarios_sedes_ver" on public.usuarios_sedes for select to authenticated
  using (usuario_id = auth.uid() or (public.es_administrador() and public.sede_de_mi_negocio(sede_id)) or public.es_dalu());
drop policy if exists "usuarios_sedes_agregar" on public.usuarios_sedes;
create policy "usuarios_sedes_agregar" on public.usuarios_sedes for insert to authenticated
  with check (public.es_administrador() and public.sede_de_mi_negocio(sede_id)
              and exists (select 1 from public.perfiles p where p.id = usuario_id and p.negocio_id = public.mi_negocio()));
drop policy if exists "usuarios_sedes_quitar" on public.usuarios_sedes;
create policy "usuarios_sedes_quitar" on public.usuarios_sedes for delete to authenticated
  using (public.es_administrador() and public.sede_de_mi_negocio(sede_id));
revoke all on public.usuarios_sedes from anon;
grant select, insert, delete on public.usuarios_sedes to authenticated;

