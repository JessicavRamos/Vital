-- =====================================================================
-- DALU Vital · v13: planes y sedes
--
-- Qué hace:
--   * Planes (Básico, Profesional, Premium) con límite de sedes, de usuarios y módulos.
--     DALU elige el plan de cada empresa y puede cambiar los números de cada plan.
--     Pet Garden queda en Premium.
--   * Sedes: cada empresa tiene una o varias. Clientes, mascotas e historial se comparten
--     en toda la empresa; la AGENDA es de cada sede y cada servicio queda con su sede.
--   * Los colaboradores quedan asignados a sedes y solo ven y manejan esas agendas;
--     el administrador ve todas.
--   * Precios por sede: la lista de razas es de la empresa, pero cada sede pone sus precios.
--   * La base de datos hace cumplir los límites de sedes y usuarios del plan.
--   * Si DALU pausa una empresa, sus usuarios no pueden ver sus datos hasta que la active.
--
-- NO borra datos: todo lo que existe queda en la "Sede principal" de cada empresa.
-- Va en una transacción (si algo falla, no cambia nada). Se puede ejecutar más de una vez.
-- Necesita el v11 (y se recomienda el v12) ya ejecutados.
-- =====================================================================
begin;

do $$ begin
  if to_regclass('public.negocios') is null then
    raise exception 'Primero ejecuta sql-v11-multinegocio.sql.';
  end if;
end $$;

-- 1) Planes ------------------------------------------------------------
create table if not exists public.planes (
  id text primary key check (id ~ '^[a-z0-9-]+$'),
  nombre text not null,
  orden int not null default 0,
  max_sedes int not null check (max_sedes >= 1),
  max_usuarios int not null check (max_usuarios >= 1),
  recordatorios boolean not null default true,
  reportes boolean not null default true,
  respaldo boolean not null default true,
  historia_clinica boolean not null default false
);
insert into public.planes (id, nombre, orden, max_sedes, max_usuarios, recordatorios, reportes, respaldo, historia_clinica) values
  ('basico', 'Básico', 1, 1, 3, true, true, true, false),
  ('profesional', 'Profesional', 2, 2, 8, true, true, true, true),
  ('premium', 'Premium', 3, 5, 20, true, true, true, true)
on conflict (id) do nothing;
alter table public.planes enable row level security;
drop policy if exists "planes_ver" on public.planes;
create policy "planes_ver" on public.planes for select to authenticated using (true);
drop policy if exists "planes_cambiar" on public.planes;
create policy "planes_cambiar" on public.planes for update to authenticated
  using (public.es_dalu()) with check (public.es_dalu());
revoke all on public.planes from anon;
grant select, update on public.planes to authenticated;

-- Plan de cada empresa (Pet Garden: Premium; las demás empiezan en Básico)
do $$ begin
  if not exists (select 1 from information_schema.columns
                 where table_schema = 'public' and table_name = 'negocios' and column_name = 'plan_id') then
    alter table public.negocios add column plan_id text not null default 'basico' references public.planes(id);
    update public.negocios set plan_id = 'premium' where id = 1;
  end if;
end $$;

-- Solo DALU cambia el plan, la dirección corta o el estado de una empresa
-- (el administrador de la empresa solo puede cambiar el nombre).
create or replace function public.proteger_negocio()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if auth.uid() is not null and not public.es_dalu()
     and (new.plan_id is distinct from old.plan_id or new.slug is distinct from old.slug
          or new.activo is distinct from old.activo) then
    raise exception 'Solo DALU puede cambiar el plan, la dirección o el estado de la empresa.';
  end if;
  return new;
end $$;
drop trigger if exists trg_proteger_negocio on public.negocios;
create trigger trg_proteger_negocio before update on public.negocios
  for each row execute function public.proteger_negocio();

-- Empresa pausada por DALU (por ejemplo, por falta de pago): sus usuarios no ven sus datos
-- hasta que la vuelva a activar. No se borra nada.
create or replace function public.mi_negocio()
returns bigint language sql stable security definer set search_path = public as $$
  select p.negocio_id from public.perfiles p join public.negocios n on n.id = p.negocio_id
  where p.id = auth.uid() and n.activo;
$$;

-- 2) Sedes -------------------------------------------------------------
create table if not exists public.sedes (
  id bigint generated by default as identity primary key,
  negocio_id bigint not null default public.mi_negocio() references public.negocios(id) on delete cascade,
  nombre text not null check (length(trim(nombre)) > 0),
  activo boolean not null default true,
  creado_en timestamptz not null default now(),
  unique (negocio_id, nombre)
);
create index if not exists sedes_negocio_idx on public.sedes (negocio_id);
alter table public.sedes enable row level security;
insert into public.sedes (negocio_id, nombre)
select n.id, 'Sede principal' from public.negocios n
where not exists (select 1 from public.sedes s where s.negocio_id = n.id);

-- Límite de sedes activas según el plan
create or replace function public.limite_sedes()
returns trigger language plpgsql security definer set search_path = public as $$
declare v_max int;
begin
  if not new.activo then return new; end if;
  if tg_op = 'UPDATE' and old.activo then return new; end if;
  select p.max_sedes into v_max from public.negocios n join public.planes p on p.id = n.plan_id where n.id = new.negocio_id;
  if (select count(*) from public.sedes where negocio_id = new.negocio_id and activo and id <> coalesce(new.id, -1)) >= v_max then
    raise exception 'Tu plan permite % sede(s). Para agregar más, cambia de plan con DALU.', v_max;
  end if;
  return new;
end $$;
drop trigger if exists trg_limite_sedes on public.sedes;
create trigger trg_limite_sedes before insert or update of activo on public.sedes
  for each row execute function public.limite_sedes();

-- 3) Colaboradores asignados a sedes -------------------------------------
create table if not exists public.usuarios_sedes (
  usuario_id uuid not null references public.perfiles(id) on delete cascade,
  sede_id bigint not null references public.sedes(id) on delete cascade,
  primary key (usuario_id, sede_id)
);
alter table public.usuarios_sedes enable row level security;
-- Quien ya existe queda en la sede principal de su empresa
insert into public.usuarios_sedes (usuario_id, sede_id)
select p.id, (select min(s.id) from public.sedes s where s.negocio_id = p.negocio_id)
from public.perfiles p
where p.negocio_id is not null
  and not exists (select 1 from public.usuarios_sedes us where us.usuario_id = p.id)
on conflict do nothing;

-- Sedes que puede ver y manejar quien inició sesión (el administrador: todas las de su empresa)
create or replace function public.mis_sedes()
returns bigint[] language sql stable security definer set search_path = public as $$
  select coalesce(case
    when public.es_administrador() then
      (select array_agg(s.id order by s.id) from public.sedes s where s.negocio_id = public.mi_negocio())
    else
      (select array_agg(us.sede_id order by us.sede_id) from public.usuarios_sedes us
         join public.sedes s on s.id = us.sede_id
        where us.usuario_id = auth.uid() and s.negocio_id = public.mi_negocio())
  end, '{}'::bigint[]);
$$;
-- Sede que se usa si no se indica otra (la primera activa de las suyas)
create or replace function public.mi_sede_predeterminada()
returns bigint language sql stable security definer set search_path = public as $$
  select s.id from public.sedes s where s.id = any(public.mis_sedes()) and s.activo order by s.id limit 1;
$$;
create or replace function public.sede_de_mi_negocio(p_sede bigint)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.sedes where id = p_sede and negocio_id = public.mi_negocio());
$$;

