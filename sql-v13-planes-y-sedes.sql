  returning id into v_cita;
  update citas set estado = 'realizada', precio_cobrado = p_precio, guia_id = p_guia_id, notas_servicio = p_notas
   where id = v_cita;
  update servicios set fecha = p_fecha where cita_id = v_cita and fecha is distinct from p_fecha;
  return v_cita;
end $$;

create or replace function public.anular_servicio(p_servicio_id bigint, p_motivo text)
returns void language plpgsql security definer set search_path = public as $$
declare
  s jsonb; c jsonb; v_cita bigint; v_nombre text; v_negocio bigint := public.mi_negocio();
begin
  if auth.uid() is null then raise exception 'Debes iniciar sesión.'; end if;
  if v_negocio is null then raise exception 'Tu usuario no tiene un negocio asignado.'; end if;
  if coalesce(trim(p_motivo), '') = '' then raise exception 'Escribe el motivo de la cancelación.'; end if;

  select to_jsonb(x) into s from servicios x
  where x.id = p_servicio_id and x.negocio_id = v_negocio and x.sede_id = any(public.mis_sedes()) for update;
  if s is null then raise exception 'El servicio no existe o ya fue cancelado.'; end if;

  v_cita := nullif(s ->> 'cita_id', '')::bigint;
  if v_cita is not null then select to_jsonb(x) into c from citas x where x.id = v_cita and x.negocio_id = v_negocio; end if;
  select nombre into v_nombre from tipos_servicio where id = nullif(s ->> 'tipo_id', '')::bigint;

  insert into servicios_anulados
    (negocio_id, sede_id, servicio_id, cita_id, mascota_id, fecha, servicio, precio_cobrado, medicado, datos, motivo, anulado_por, anulado_por_id)
  values
    (v_negocio, nullif(s ->> 'sede_id', '')::bigint, p_servicio_id, v_cita,
     coalesce(nullif(s ->> 'mascota_id', '')::bigint, nullif(c ->> 'mascota_id', '')::bigint),
     nullif(s ->> 'fecha', '')::date, v_nombre, nullif(s ->> 'precio_cobrado', '')::numeric,
     coalesce((s ->> 'medicado')::boolean, false), s, trim(p_motivo), usuario_actual(), auth.uid());

  delete from servicios where id = p_servicio_id and negocio_id = v_negocio;

  if v_cita is not null then
    update citas set estado = 'cancelada', cancelada_por = usuario_actual(),
                     cancelada_en = now(), motivo_cancelacion = trim(p_motivo)
    where id = v_cita and negocio_id = v_negocio;
  end if;
end $$;

create or replace function public.cancelar_cita(p_cita_id bigint, p_motivo text)
returns void language plpgsql security definer set search_path = public as $$
declare v_serv bigint; v_negocio bigint := public.mi_negocio();
begin
  if auth.uid() is null then raise exception 'Debes iniciar sesión.'; end if;
  if v_negocio is null then raise exception 'Tu usuario no tiene un negocio asignado.'; end if;
  if coalesce(trim(p_motivo), '') = '' then raise exception 'Escribe el motivo de la cancelación.'; end if;
  if not exists (select 1 from citas where id = p_cita_id and negocio_id = v_negocio and sede_id = any(public.mis_sedes())) then
    raise exception 'La cita no existe o ya estaba cancelada.';
  end if;

  select id into v_serv from servicios where cita_id = p_cita_id and negocio_id = v_negocio limit 1;
  if v_serv is not null then
    perform anular_servicio(v_serv, p_motivo);
  else
    update citas set estado = 'cancelada', cancelada_por = usuario_actual(),
                     cancelada_en = now(), motivo_cancelacion = trim(p_motivo)
    where id = p_cita_id and negocio_id = v_negocio and estado <> 'cancelada';
    if not found then raise exception 'La cita no existe o ya estaba cancelada.'; end if;
  end if;
end $$;

-- 10) Invitaciones con sedes y límite de usuarios del plan --------------------
alter table public.invitaciones add column if not exists sedes bigint[];

drop function if exists public.invitar_usuario(text, text, bigint);
drop function if exists public.invitar_usuario(text, text, bigint, bigint[]);
create function public.invitar_usuario(p_correo text, p_rol text default 'empleado',
                                       p_negocio_id bigint default null, p_sedes bigint[] default null)
returns text language plpgsql security definer set search_path = public as $$
declare
  v_correo text := lower(trim(p_correo));
  v_negocio bigint;
  v_usuario uuid;
  v_actual bigint;
  v_max int;
  v_sedes bigint[];
begin
  if auth.uid() is null then raise exception 'Debes iniciar sesión.'; end if;
  v_negocio := case when public.es_dalu() and p_negocio_id is not null then p_negocio_id else public.mi_negocio() end;
  if v_negocio is null then raise exception 'Tu usuario no tiene un negocio asignado.'; end if;
  if not (public.es_dalu() or (public.es_administrador() and v_negocio = public.mi_negocio())) then
    raise exception 'Solo el administrador puede invitar usuarios.';
  end if;
  if coalesce(p_rol, '') not in ('administrador', 'empleado') then raise exception 'Rol no válido.'; end if;
  if v_correo !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' then raise exception 'Escribe un correo válido.'; end if;

  -- Sedes válidas de esa empresa (si no se elige ninguna: la sede principal)
  select array_agg(id order by id) into v_sedes from public.sedes
  where negocio_id = v_negocio and id = any(coalesce(p_sedes, '{}'::bigint[]));
  if v_sedes is null then
    select array[min(id)] into v_sedes from public.sedes where negocio_id = v_negocio;
  end if;

  -- Límite de usuarios del plan (cuentan las cuentas y las invitaciones pendientes)
  select p.max_usuarios into v_max from public.negocios n join public.planes p on p.id = n.plan_id where n.id = v_negocio;
  if (select count(*) from public.perfiles where negocio_id = v_negocio)
     + (select count(*) from public.invitaciones where negocio_id = v_negocio and correo <> v_correo) >= v_max then
    raise exception 'Tu plan permite % usuarios. Para agregar más, cambia de plan con DALU.', v_max;
  end if;

  -- ¿Ya tiene cuenta? Se asigna directo (solo si no pertenece a otra empresa).
  select id into v_usuario from auth.users where lower(email) = v_correo;
  if v_usuario is not null then
    select negocio_id into v_actual from public.perfiles where id = v_usuario;
    if v_actual is not null then
      raise exception 'Ese correo ya tiene acceso a un negocio y no se puede invitar.';
    end if;
    insert into public.perfiles (id, correo, negocio_id, rol) values (v_usuario, v_correo, v_negocio, p_rol)
    on conflict (id) do update set negocio_id = excluded.negocio_id, rol = excluded.rol;
    insert into public.usuarios_sedes (usuario_id, sede_id) select v_usuario, unnest(v_sedes) on conflict do nothing;
    return 'asignado';
  end if;

  if exists (select 1 from public.invitaciones where correo = v_correo and negocio_id <> v_negocio)
     and not public.es_dalu() then
    raise exception 'Ese correo ya tiene una invitación pendiente de otro negocio.';
  end if;
  insert into public.invitaciones (correo, negocio_id, rol, creado_por, sedes)
  values (v_correo, v_negocio, p_rol, auth.uid(), v_sedes)
  on conflict (correo) do update set negocio_id = excluded.negocio_id, rol = excluded.rol,
                                     creado_por = excluded.creado_por, creado_en = now(), sedes = excluded.sedes;
  return 'invitado';
end $$;

-- Al crear la cuenta: queda en su empresa, con su rol y en sus sedes
create or replace function public.crear_perfil_usuario()
returns trigger language plpgsql security definer set search_path = public as $$
declare v_inv public.invitaciones%rowtype;
begin
  if tg_op = 'INSERT' then
    select * into v_inv from public.invitaciones where correo = lower(new.email);
    if not found and not exists (select 1 from public.perfiles where id = new.id) then
      raise exception 'El correo % no tiene una invitación. Pide al administrador de tu negocio que te invite.', new.email;
    end if;
    insert into public.perfiles (id, correo, nombre, negocio_id, rol)
    values (new.id, new.email, nullif(trim(new.raw_user_meta_data ->> 'nombre'), ''),
            v_inv.negocio_id, coalesce(v_inv.rol, 'empleado'))
    on conflict (id) do update set correo = excluded.correo,
                                   nombre = coalesce(excluded.nombre, public.perfiles.nombre);
    if v_inv.negocio_id is not null then
      insert into public.usuarios_sedes (usuario_id, sede_id)
      select new.id, s.id from public.sedes s
      where s.negocio_id = v_inv.negocio_id
        and s.id = any(coalesce(v_inv.sedes, array[(select min(id) from public.sedes where negocio_id = v_inv.negocio_id)]))
      on conflict do nothing;
    end if;
    delete from public.invitaciones where correo = lower(new.email);
  else
    update public.perfiles
       set correo = new.email,
           nombre = coalesce(nullif(trim(new.raw_user_meta_data ->> 'nombre'), ''), nombre)
     where id = new.id;
  end if;
  return new;
end $$;

-- Crear empresa (solo DALU): con su plan y su sede principal
drop function if exists public.crear_negocio(text, text, text);
drop function if exists public.crear_negocio(text, text, text, text);
create function public.crear_negocio(p_nombre text, p_slug text, p_correo_admin text, p_plan text default 'basico')
returns bigint language plpgsql security definer set search_path = public as $$
declare v_id bigint;
begin
  if not public.es_dalu() then raise exception 'Solo DALU puede crear negocios.'; end if;
  insert into public.negocios (nombre, slug, plan_id) values (trim(p_nombre), lower(trim(p_slug)), coalesce(p_plan, 'basico'))
  returning id into v_id;
  insert into public.sedes (negocio_id, nombre) values (v_id, 'Sede principal');

  insert into public.grupos_recordatorio (negocio_id, nombre, frecuencia_dias)
  select v_id, nombre, frecuencia_dias from public.grupos_recordatorio where negocio_id = 1;
  insert into public.tipos_servicio (negocio_id, nombre, grupo_id)
  select v_id, t.nombre, g2.id
  from public.tipos_servicio t
  join public.grupos_recordatorio g on g.id = t.grupo_id
  join public.grupos_recordatorio g2 on g2.negocio_id = v_id and g2.nombre = g.nombre
  where t.negocio_id = 1;

  perform public.invitar_usuario(p_correo_admin, 'administrador', v_id);
  return v_id;
end $$;

-- Uso de cada empresa frente a su plan (solo DALU)
create or replace function public.uso_negocios()
returns table(negocio_id bigint, sedes int, usuarios int, invitaciones int)
language plpgsql stable security definer set search_path = public as $$
begin
  if not public.es_dalu() then raise exception 'Solo DALU puede ver el uso de las empresas.'; end if;
  return query
  select n.id,
         (select count(*)::int from public.sedes s where s.negocio_id = n.id and s.activo),
         (select count(*)::int from public.perfiles p where p.negocio_id = n.id),
         (select count(*)::int from public.invitaciones i where i.negocio_id = n.id)
  from public.negocios n;
end $$;

