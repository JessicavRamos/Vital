-- 5) Precios por sede -------------------------------------------------------
create table if not exists public.precios_sede (
  negocio_id bigint not null default public.mi_negocio() references public.negocios(id) on delete cascade,
  sede_id bigint not null references public.sedes(id) on delete cascade,
  raza_id bigint not null references public.razas(id) on delete cascade,
  precio_bano numeric, precio_corte numeric, precio_corte_bano numeric, precio_unas numeric, recargo_medicado numeric,
  primary key (sede_id, raza_id)
);
create index if not exists precios_sede_negocio_idx on public.precios_sede (negocio_id);
alter table public.precios_sede enable row level security;
-- Los precios que ya tenías quedan en la sede principal
insert into public.precios_sede (negocio_id, sede_id, raza_id, precio_bano, precio_corte, precio_corte_bano, precio_unas, recargo_medicado)
select r.negocio_id, (select min(s.id) from public.sedes s where s.negocio_id = r.negocio_id), r.id,
       r.precio_bano, r.precio_corte, r.precio_corte_bano, r.precio_unas, r.recargo_medicado
from public.razas r
where coalesce(r.precio_bano, r.precio_corte, r.precio_corte_bano, r.precio_unas, r.recargo_medicado) is not null
on conflict do nothing;

-- Una sede nueva arranca con los precios de la sede más antigua (después se cambian)
create or replace function public.copiar_precios_sede_nueva()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.precios_sede (negocio_id, sede_id, raza_id, precio_bano, precio_corte, precio_corte_bano, precio_unas, recargo_medicado)
  select new.negocio_id, new.id, p.raza_id, p.precio_bano, p.precio_corte, p.precio_corte_bano, p.precio_unas, p.recargo_medicado
  from public.precios_sede p
  where p.sede_id = (select min(id) from public.sedes where negocio_id = new.negocio_id and id <> new.id)
  on conflict do nothing;
  return new;
end $$;
drop trigger if exists trg_copiar_precios_sede on public.sedes;
create trigger trg_copiar_precios_sede after insert on public.sedes
  for each row execute function public.copiar_precios_sede_nueva();

