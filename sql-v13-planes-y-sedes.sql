create function public.registrar_visita_anterior(
  p_mascota_id bigint, p_tipo_id bigint, p_fecha date, p_hora text default '10:00',
  p_precio numeric default null, p_guia_id bigint default null, p_notas text default null,
  p_medicado boolean default false, p_recargo numeric default null, p_sede_id bigint default null)
returns bigint language plpgsql set search_path = public as $$
declare
  v_cita bigint;
  v_hoy date := (now() at time zone 'America/Bogota')::date;
  v_sede bigint := coalesce(p_sede_id, public.mi_sede_predeterminada());
begin
  if p_fecha is null or p_fecha > v_hoy then
    raise exception 'La fecha de la visita anterior no puede ser futura.';
  end if;
  if p_tipo_id is null then
    raise exception 'Elige el servicio de la visita.';
  end if;
  if v_sede is null or not (v_sede = any(public.mis_sedes())) then
    raise exception 'No tienes acceso a esa sede.';
  end if;
  insert into citas (sede_id, mascota_id, tipo_id, fecha_hora, precio_acordado, estado, medicado, recargo_medicado)
  values (v_sede, p_mascota_id, p_tipo_id, ((p_fecha::text || ' ' || coalesce(p_hora, '10:00'))::timestamp at time zone 'America/Bogota'),
