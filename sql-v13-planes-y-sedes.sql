create policy "sedes_cambiar" on public.sedes for update to authenticated
  using (negocio_id = (select public.mi_negocio()) and public.es_administrador())
  with check (negocio_id = (select public.mi_negocio()) and public.es_administrador());
revoke all on public.sedes from anon;
